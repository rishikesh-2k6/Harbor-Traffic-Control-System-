def main() -> int:
    parser = argparse.ArgumentParser(
        description="Groq AI Validation for Harbor Simulator Telemetry."
    )
    parser.add_argument("--samples", type=int, default=5, help="Number of CSV samples to validate")
    parser.add_argument("--csv", default="collected_data.csv", help="Path to collected_data.csv")
    parser.add_argument("--live", action="store_true", help="Validate live simulation state instead of CSV")
    parser.add_argument("--model", default="openai/gpt-oss-120b", help="Groq model to use")
    parser.add_argument("--api-key", default=None, help="Groq API key (defaults to GROQ_API_KEY env var)")
    parser.add_argument("--out", default="logs/ai_validation_report.json", help="Path to save output report (JSON or MD)")
    args = parser.parse_args()

    validator = GroqDataValidator(api_key=args.api_key, model=args.model)

    print("=" * 70)
    print(" HARBOR TRAFFIC CONTROL SYSTEM - AI DATA VALIDATION")
    print(f" Groq LLM Engine: {validator.model} | Active: {validator.has_active_api()}")
    print("=" * 70)

    script_dir = os.path.dirname(os.path.abspath(__file__))
    csv_full = os.path.join(script_dir, args.csv) if not os.path.isabs(args.csv) else args.csv
    out_full = os.path.join(script_dir, args.out) if not os.path.isabs(args.out) else args.out

    if args.live:
        print("[AI Validator] Gathering live simulation telemetry (currents, vessels, acoustics)...")
        res = validator.validate_live_simulation()
    else:
        if not os.path.exists(csv_full):
            print(f"[AI Validator] {csv_full} not found. Running live simulation validation instead.")
            res = validator.validate_live_simulation()
        else:
            print(f"[AI Validator] Sampling {args.samples} detection records from {args.csv}...")
            res = validator.validate_from_collected_csv(csv_path=csv_full, n_samples=args.samples)

    report_md = format_markdown_report(res)
    print("\n" + report_md + "\n")

    save_validation_report(res, out_full)
    return 0


if __name__ == "__main__":
    sys.exit(main())
