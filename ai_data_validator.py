# 3. Groq Data Validator Class
# ─────────────────────────────────────────────────────────────────────────────

class GroqDataValidator:
    """
    Evaluates synthetic harbor monitoring telemetry using the Groq API.
    """

    PREFERRED_MODELS = [
        "openai/gpt-oss-120b",
        "llama-3.3-70b-versatile",
        "qwen/qwen3.8-27b",
        "openai/gpt-oss-20b",
        "llama-3.1-70b-versatile",
        "llama-3.1-8b-instant"
    ]

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "openai/gpt-oss-120b"
    ):
        self.api_key = api_key or os.environ.get("GROQ_API_KEY") or os.environ.get("GROQ_KEY")
        if not self.api_key:
            env_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env")
            if os.path.exists(env_path):
                try:
                    with open(env_path, "r", encoding="utf-8") as f:
                        for line in f:
                            line = line.strip()
                            if line.startswith("GROQ_API_KEY="):
                                self.api_key = line.split("=", 1)[1].strip().strip('"').strip("'")
                                break
                except Exception:
                    pass

        self.model = model
        self.client: Optional[Any] = None

        if self.api_key and GROQ_AVAILABLE:
            try:
                self.client = Groq(api_key=self.api_key)
                # Auto-select highest capability model available on this key
                try:
                    available = [m.id for m in self.client.models.list().data]
                    for candidate in self.PREFERRED_MODELS:
                        if candidate in available:
                            self.model = candidate
                            break
                except Exception:
                    pass
            except Exception as exc:
                print(f"[GroqValidator] Warning: Failed to initialize Groq client: {exc}")
                self.client = None

    def has_active_api(self) -> bool:
        return self.client is not None

    def validate_telemetry_payload(
        self,
        current_data: Optional[Dict[str, Any]] = None,
        vessel_data: Optional[List[Dict[str, Any]]] = None,
        acoustic_data: Optional[List[Dict[str, Any]]] = None,
        scenario_meta: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Validates the supplied telemetry data using Groq API (or heuristic fallback).
        """
        if not self.has_active_api():
            return _local_heuristic_validation(current_data, vessel_data, acoustic_data)

        # Build concise JSON payload for Groq
        clean_acoustics = []
        if acoustic_data:
            key_cols = [
                "Sound_Speed_mps", "Received_Level_dB", "Source_Level_dB",
                "Transmission_Loss_dB", "SNR_dB", "Ambient_Noise_dB",
                "Frequency_Hz", "Doppler_Shift_Hz", "Water_Temp_C", "Salinity_ppt",
                "Sensor_Depth_m", "Sea_State", "Wind_Speed_knots"
            ]
            for row in acoustic_data[:5]:
                clean_row = {}
                for k in key_cols:
                    if k in row:
                        val = row[k]
                        try:
                            clean_row[k] = round(abs(float(val)), 2) if k == "Sensor_Depth_m" else round(float(val), 2)
                        except (ValueError, TypeError):
                            clean_row[k] = val
                clean_acoustics.append(clean_row if clean_row else row)

        payload = {
            "simulation_scenario": scenario_meta or {"name": "Active Scenario", "season": "MONSOON/NORMAL"},
            "ocean_current_telemetry": current_data or {},
            "vessel_samples": (vessel_data or [])[:5],
            "acoustic_sensor_samples": clean_acoustics
        }

        user_content = (
            "Analyze the following synthetic harbor telemetry batch and output strictly valid JSON conforming to the schema:\n\n"
            f"{json.dumps(payload, indent=2, default=str)}"
        )

        last_error = None
        for attempt in range(2):
            try:
                assert self.client is not None
                kwargs: Dict[str, Any] = {
                    "model": self.model,
                    "messages": [
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": user_content}
                    ],
                    "temperature": 0.1,
                    "max_tokens": 2400
                }
                if attempt == 0:
                    kwargs["response_format"] = {"type": "json_object"}

                response = self.client.chat.completions.create(**kwargs)

                raw_reply = response.choices[0].message.content or "{}"
                cleaned = raw_reply.strip()
                if cleaned.startswith("```"):
                    cleaned = cleaned.split("\n", 1)[1]
                    if cleaned.endswith("```"):
                        cleaned = cleaned.rsplit("```", 1)[0]
                result = json.loads(cleaned.strip())
                result["_meta"] = {
                    "engine": "groq_llm",
                    "model": self.model,
                    "attempt": attempt + 1,
                    "timestamp": datetime.now().isoformat()
                }
                return result
            except Exception as exc:
                last_error = exc
                time.sleep(0.4)

        print(f"[GroqValidator] Error calling Groq API ({last_error}). Falling back to local physics validation.")
        fallback = _local_heuristic_validation(current_data, vessel_data, acoustic_data)
        fallback["_meta"]["groq_call_error"] = str(last_error)
        return fallback

    def validate_from_collected_csv(
        self,
        csv_path: str = "collected_data.csv",
        n_samples: int = 5
    ) -> Dict[str, Any]:
        """
        Extracts sample rows from collected_data.csv and validates them.
        """
        import pandas as pd
        if not os.path.exists(csv_path):
            raise FileNotFoundError(f"Cannot find CSV at {csv_path}")

        # Read sample rows
        try:
            df = pd.read_csv(csv_path, nrows=500)
            if len(df) == 0:
                raise ValueError("CSV is empty.")
            sample_df = df.sample(min(n_samples, len(df)), random_state=42)
            acoustic_rows = sample_df.to_dict(orient="records")
        except Exception as exc:
            raise RuntimeError(f"Error reading CSV samples: {exc}")

        # Extract vessel representations from sample
        vessels = []
        for r in acoustic_rows:
            vessels.append({
                "type": r.get("Actual_Type", "Unknown"),
                "true_weight_kg": int(float(r.get("Actual_Weight_kg", 0))),
                "speed_knots": round(float(r.get("Actual_Speed_knots", 0)), 1),
                "draft_m": round(abs(float(r.get("Actual_Depth_m", 5))), 1)
            })

        # Synthesize current telemetry matching the rows' Sea_State
        sea_state = int(sample_df["Sea_State"].iloc[0]) if "Sea_State" in sample_df else 3
        current_info = {
            "intensity_mps": 0.35 if sea_state <= 3 else 3.2,
            "surge_level": 0.1 if sea_state <= 3 else 2.8,
            "wave_height": 0.4 if sea_state <= 3 else 6.1,
            "sea_state": sea_state
        }

        scenario_meta = {
            "name": "Collected Data Validation",
            "samples_analyzed": len(acoustic_rows),
            "csv_path": csv_path
        }

        return self.validate_telemetry_payload(
            current_data=current_info,
            vessel_data=vessels,
            acoustic_data=acoustic_rows,
            scenario_meta=scenario_meta
        )

    def validate_live_simulation(self) -> Dict[str, Any]:
        """
        Gathers live simulation state from simulator.py and auv.py, then validates.
        """
        import simulator as sim

        current_info = sim.get_monsoon_current_info()
        active_scenario = sim.get_active_scenario()
        fleet = sim.generate_fleet()

        vessels = []
        for v in fleet[:6]:
            vessels.append({
                "type": v.get("type"),
                "true_weight": v.get("true_weight"),
                "speed_knots": v.get("speed_knots"),
                "draft": v.get("draft")
            })

        # Generate a small sample of acoustic sensor detections
        sensors = sim.generate_sensors()
        sim.collect_sensor_detections(fleet, sensors, frame=10)

        # Pull tail rows from collected_data.csv if exists
        acoustic_rows: List[Dict[str, Any]] = []
        if os.path.exists(sim.COLLECTED_FILE):
            try:
                import pandas as pd
                df_tail = pd.read_csv(sim.COLLECTED_FILE, low_memory=False).tail(6)
                acoustic_rows = df_tail.to_dict(orient="records")
            except Exception:
                pass

        return self.validate_telemetry_payload(
            current_data=current_info,
            vessel_data=vessels,
            acoustic_data=acoustic_rows,
            scenario_meta=active_scenario
        )


