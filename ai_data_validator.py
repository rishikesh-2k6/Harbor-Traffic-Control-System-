def format_markdown_report(result: Dict[str, Any]) -> str:
    """Format validation result dictionary as an executive markdown report."""
    plausibility = result.get("real_world_plausibility_pct", 0.0)
    verdict = result.get("verdict", "UNKNOWN")
    scores = result.get("category_scores", {})
    engine = result.get("_meta", {}).get("engine", "unknown")
    
    badge = (
        "[HIGH FIDELITY]" if plausibility >= 85 else
        "[PLAUSIBLE / SCALED]" if plausibility >= 65 else
        "[UNPHYSICAL]"
    )

    lines = [
        "# AI Data Validation Report: Real-World Maritime Plausibility",
        f"**Generated**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  |  **Engine**: `{engine}`",
        "",
        f"## Overall Real-World Plausibility: **{plausibility}%** [{verdict} — {badge}]",
        "",
        "### Subsystem Realism Breakdown",
        f"| Telemetry Domain | Plausibility Score | Status |",
        f"| :--- | :--- | :--- |",
        f"| **Ocean Hydrodynamics & Currents** | `{scores.get('currents_plausibility_pct', 0)}%` | {'[OK] Nominal' if scores.get('currents_plausibility_pct', 0) >= 80 else '[WARN] Review'} |",
        f"| **Vessel Tonnage & Weights** | `{scores.get('vessel_weights_plausibility_pct', 0)}%` | {'[OK] Nominal' if scores.get('vessel_weights_plausibility_pct', 0) >= 80 else '[INFO] Synthetic Scale'} |",
        f"| **Underwater Acoustic Physics** | `{scores.get('acoustics_plausibility_pct', 0)}%` | {'[OK] Nominal' if scores.get('acoustics_plausibility_pct', 0) >= 80 else '[WARN] Review'} |",
        f"| **Environmental Conditions** | `{scores.get('environmental_plausibility_pct', 0)}%` | {'[OK] Nominal' if scores.get('environmental_plausibility_pct', 0) >= 80 else '[WARN] Review'} |",
        "",
        "### Expert Physical Assessment",
    ]

    summary_text = result.get("expert_summary") or result.get("summary")
    if not summary_text:
        eval_count = result.get("parameters_evaluated_count", "multiple")
        summary_text = (
            f"Groq LLM evaluated {eval_count} telemetry parameters across ocean hydrodynamics, naval "
            f"architecture, and acoustic propagation. Overall physical plausibility is scored at {plausibility}%. "
            f"Underwater acoustics scored {scores.get('acoustics_plausibility_pct', 0)}%, vessel displacement and speed "
            f"scored {scores.get('vessel_weights_plausibility_pct', 0)}%, and ocean current dynamics scored "
            f"{scores.get('currents_plausibility_pct', 0)}%."
        )
    lines.append(summary_text)
    lines.append("")

    violations = result.get("critical_violations", [])
    if violations:
        lines.append("### Physical Anomalies / Rule Deviations Detected")
        for v in violations:
            lines.append(
                f"- **{v.get('parameter')}** (`{v.get('severity', 'WARN')}`): Observed `{v.get('observed_value')}` "
                f"(Expected: `{v.get('realistic_expected_range')}`). *Reason*: {v.get('reason')}"
            )
        lines.append("")

    scaling = result.get("synthetic_scaling_observations", [])
    if scaling:
        lines.append("### Synthetic Scaling vs Real-World Context")
        for s in scaling:
            lines.append(f"- {s}")
        lines.append("")

    recs = result.get("calibration_recommendations", [])
    if recs:
        lines.append("### Recommended Simulator Calibrations")
        for r in recs:
            lines.append(f"1. {r}")
        lines.append("")

    return "\n".join(lines)


def save_validation_report(result: Dict[str, Any], filepath: str) -> None:
    """Save validation result as JSON or Markdown."""
    os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
    if filepath.endswith(".md"):
        md_text = format_markdown_report(result)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(md_text)
    else:
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=2)
    print(f"[AI Validator] Report saved to: {filepath}")


